SPI_SOURCE = """\
/* Generated by fwcopilot from board.yaml. Confirm the command framing against:
 * {datasheet_hint}
 * In particular: the read/write bit position in the command byte, whether the
 * device needs dummy cycles, and the maximum SCK frequency.
 */
#include "{header}"

/* TODO: many SPI devices set bit 7 of the command byte for reads — verify. */
#define {tag}_READ_FLAG  0x80u

int {lname}_read_reg({lname}_t *dev, uint8_t reg, uint8_t *value)
{{
    uint8_t tx[2];
    uint8_t rx[2] = {{0u, 0u}};
    int rc;

    if (dev == NULL || dev->xfer == NULL || value == NULL) {{
        return -1;
    }}
    tx[0] = (uint8_t)(reg | {tag}_READ_FLAG);
    tx[1] = 0x00u;

    if (dev->cs != NULL) {{
        dev->cs(true, dev->ctx);
    }}
    rc = dev->xfer(tx, rx, sizeof(tx), dev->ctx);
    if (dev->cs != NULL) {{
        dev->cs(false, dev->ctx);
    }}
    if (rc == 0) {{
        *value = rx[1];
    }}
    return rc;
}}

int {lname}_write_reg({lname}_t *dev, uint8_t reg, uint8_t value)
{{
    uint8_t tx[2];
    int rc;

    if (dev == NULL || dev->xfer == NULL) {{
        return -1;
    }}
    tx[0] = (uint8_t)(reg & (uint8_t)~{tag}_READ_FLAG);
    tx[1] = value;

    if (dev->cs != NULL) {{
        dev->cs(true, dev->ctx);
    }}
    rc = dev->xfer(tx, NULL, sizeof(tx), dev->ctx);
    if (dev->cs != NULL) {{
        dev->cs(false, dev->ctx);
    }}
    return rc;
}}

int {lname}_init({lname}_t *dev)
{{
    if (dev == NULL || dev->xfer == NULL) {{
        return -1;
    }}
    /* TODO: verify the device ID register and run the datasheet reset sequence. */
    return 0;
}}
"""


def gen_drivers(board: BoardProfile) -> List[Tuple[str, str]]:
    files: List[Tuple[str, str]] = []
    for comp in board.components:
        bus_type = _bus_type(board, comp)
        base = _lower(comp.part or comp.ref)
        header_name = f"drivers/{base}.h"
        hint = comp.datasheet or f"(no datasheet linked for {comp.part or comp.ref} in board.yaml)"
        common = {
            "part": comp.part or comp.ref,
            "ref": comp.ref,
            "role_comment": f" — {comp.role}" if comp.role else "",
            "bus": comp.bus_name or "unspecified",
            "guard": _header_guard(base),
            "tag": _upper(base),
            "lname": base,
            "header": f"{base}.h",
            "datasheet_hint": hint,
        }
        if bus_type == "spi":
            cs = comp.bus.get("cs")
            files.append((header_name, SPI_HEADER.format(
                cs_comment=f", CS={cs}" if cs else "", **common)))
            files.append((f"drivers/{base}.c", SPI_SOURCE.format(**common)))
        elif bus_type == "i2c":
            files.append((header_name, I2C_HEADER.format(
                addr=_addr_literal(comp.address if comp.address is not None else 0), **common)))
            files.append((f"drivers/{base}.c", I2C_SOURCE.format(
                addr=_addr_literal(comp.address if comp.address is not None else 0), **common)))
    return files


def _bus_type(board: BoardProfile, comp: Component) -> str:
    declared = str(comp.bus.get("type") or "").lower()
    if declared:
        return declared
    for bus in board.buses:
        if str(bus.get("name")) == comp.bus_name:
            return str(bus.get("type") or "").lower()
    if comp.address is not None:
        return "i2c"
    if comp.bus.get("cs"):
        return "spi"
    return "unknown"


