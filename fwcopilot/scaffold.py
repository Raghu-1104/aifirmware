def gen_linker_script(board: BoardProfile) -> str:
    mcu = board.mcu
    flash_kb = int(mcu.get("flash_kb") or 256)
    ram_kb = int(mcu.get("ram_kb") or 64)
    flash_origin = mcu.get("flash_origin") or "0x08000000"
    ram_origin = mcu.get("ram_origin") or "0x20000000"
    return f"""\
/* Generated by fwcopilot from board.yaml ({mcu.get('part', 'unknown MCU')}).
 * Verify ORIGIN/LENGTH against the MCU datasheet memory map before flashing.
 */
ENTRY(Reset_Handler)

MEMORY
{{
    FLASH (rx)  : ORIGIN = {flash_origin}, LENGTH = {flash_kb}K
    RAM   (rwx) : ORIGIN = {ram_origin}, LENGTH = {ram_kb}K
}}

_estack = ORIGIN(RAM) + LENGTH(RAM);
_Min_Heap_Size  = 0x200;
_Min_Stack_Size = 0x400;

SECTIONS
{{
    .isr_vector : {{ KEEP(*(.isr_vector)) }} > FLASH

    .text :
    {{
        . = ALIGN(4);
        *(.text) *(.text*)
        *(.rodata) *(.rodata*)
        . = ALIGN(4);
        _etext = .;
    }} > FLASH

    .ARM.exidx : {{ *(.ARM.exidx*) }} > FLASH

    _sidata = LOADADDR(.data);
    .data :
    {{
        . = ALIGN(4);
        _sdata = .;
        *(.data) *(.data*)
        . = ALIGN(4);
        _edata = .;
    }} > RAM AT> FLASH

    .bss :
    {{
        . = ALIGN(4);
        _sbss = .;
        *(.bss) *(.bss*) *(COMMON)
        . = ALIGN(4);
        _ebss = .;
    }} > RAM

    ._user_heap_stack :
    {{
        . = ALIGN(8);
        . = . + _Min_Heap_Size;
        . = . + _Min_Stack_Size;
        . = ALIGN(8);
    }} > RAM
}}
"""


