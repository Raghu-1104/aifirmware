def generate(board: BoardProfile, target: str) -> List[Tuple[str, str]]:
    """Return [(relative path, content)] for the chosen target."""
    if target not in TARGETS:
        raise ValueError(f"unknown target '{target}'; choose from {', '.join(TARGETS)}")
    if not board.exists:
        raise ValueError("no board.yaml found — run `fwcopilot board init` first")

    files: List[Tuple[str, str]] = [("board_pins.h", gen_board_pins(board))]
    files.extend(gen_drivers(board))

    if target == "drivers-only":
        return files

    if target == "cmsis-bare":
        files.append(("main.c", gen_main(board)))
        files.append(("startup.c", STARTUP_C))
        files.append((f"{_lower(board.name)}.ld", gen_linker_script(board)))
        files.append(("Makefile", gen_makefile(board)))
    elif target == "platformio":
        files.append(("src/main.c", gen_main(board)))
        files.append(("platformio.ini", gen_platformio(board)))
    elif target == "zephyr":
        files.append(("src/main.c", ZEPHYR_MAIN))
        files.append(("prj.conf", gen_zephyr_prj(board)))
        files.append(("CMakeLists.txt", ZEPHYR_CMAKE))
        files.append((f"boards/{_lower(board.name)}.overlay", gen_zephyr_overlay(board)))
    return files


def write_files(
    out_dir: Path, files: List[Tuple[str, str]], *, force: bool = False
) -> List[GeneratedFile]:
    written: List[GeneratedFile] = []
    for rel, content in files:
        path = out_dir / rel
        existed = path.exists()
        if existed and not force:
            written.append(GeneratedFile(rel, content, existed=True))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(GeneratedFile(rel, content, existed=existed))
    return written
