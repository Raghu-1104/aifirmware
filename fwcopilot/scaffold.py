"""Deterministic firmware code generation from the board profile.

Nothing here calls the model: given `board.yaml`, the pin map, buses and device
addresses are already exact, so the pin header, driver skeletons, linker script
and build files are generated directly. The assistant then works *on top of*
generated code that already matches the hardware.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from .board import BoardProfile, Component

TARGETS = ("cmsis-bare", "platformio", "zephyr", "drivers-only")


@dataclass
class GeneratedFile:
    path: str
    content: str
    existed: bool = False


def _ident(text: str) -> str:
    out = re.sub(r"[^A-Za-z0-9]+", "_", str(text)).strip("_")
    return out or "dev"


def _upper(text: str) -> str:
    return _ident(text).upper()


def _lower(text: str) -> str:
    return _ident(text).lower()


def _addr_literal(value: Any) -> str:
    if isinstance(value, int):
        return f"0x{value:02X}"
    text = str(value).strip()
    if text.lower().startswith("0x"):
        return "0x" + text[2:].upper()
    try:
        return f"0x{int(text):02X}"
    except ValueError:
        return text


def _header_guard(name: str) -> str:
    return _upper(name) + "_H"


# --------------------------------------------------------------------------
# board_pins.h — the highest-value generated artifact
# --------------------------------------------------------------------------

def gen_board_pins(board: BoardProfile) -> str:
    name = _upper(board.name)
    lines = [
        "/* Generated by fwcopilot from board.yaml — do not edit by hand.",
        f" * Board: {board.name}"
        + (f" rev {board.board.get('revision')}" if board.board.get("revision") else ""),
        " * Regenerate with: fwcopilot scaffold --target drivers-only",
        " */",
        f"#ifndef {name}_PINS_H",
        f"#define {name}_PINS_H",
        "",
        "#include <stdint.h>",
        "",
    ]

    mcu = board.mcu
    if mcu:
        lines.append("/* MCU */")
        if mcu.get("part"):
            lines.append(f'#define BOARD_MCU_PART        "{mcu["part"]}"')
        if mcu.get("clock_hz"):
            lines.append(f"#define BOARD_SYSCLK_HZ       {int(mcu['clock_hz'])}u")
        if mcu.get("flash_kb"):
            lines.append(f"#define BOARD_FLASH_BYTES     ({int(mcu['flash_kb'])}u * 1024u)")
        if mcu.get("ram_kb"):
            lines.append(f"#define BOARD_RAM_BYTES       ({int(mcu['ram_kb'])}u * 1024u)")
        lines.append("")

    if board.pins:
        lines.append("/* Pin map (net name -> MCU pin) */")
        width = max((len(_upper(p.get("net") or p.get("function") or p.get("pin"))) for p in board.pins), default=8)
        for pin in board.pins:
            net = _upper(pin.get("net") or pin.get("function") or pin.get("pin"))
            pad = " " * max(1, width + 4 - len(net))
            comment_bits = []
            if pin.get("function"):
                comment_bits.append(str(pin["function"]))
            if pin.get("af") is not None:
                comment_bits.append(f"AF{pin['af']}")
            if pin.get("to"):
                comment_bits.append(f"-> {pin['to']}")
            if pin.get("active"):
                comment_bits.append(f"active-{pin['active']}")
            comment = f"  /* {', '.join(comment_bits)} */" if comment_bits else ""
            lines.append(f'#define PIN_{net}{pad}"{pin.get("pin")}"{comment}')
        lines.append("")

    if board.buses:
        lines.append("/* Buses */")
        for bus in board.buses:
            bus_id = _upper(bus.get("name"))
            if bus.get("speed_hz"):
                lines.append(f"#define BUS_{bus_id}_HZ          {int(bus['speed_hz'])}u")
            if bus.get("baud"):
                lines.append(f"#define BUS_{bus_id}_BAUD        {int(bus['baud'])}u")
            for role, pin in (bus.get("pins") or {}).items():
                lines.append(f'#define BUS_{bus_id}_{_upper(role)}{" " * 8}"{pin}"')
        lines.append("")

    comps = board.components
    if comps:
        lines.append("/* On-board devices */")
        for comp in comps:
            tag = _upper(comp.part or comp.ref)
            if comp.address is not None:
                lines.append(f"#define {tag}_I2C_ADDR         {_addr_literal(comp.address)}u")
            if comp.bus_name:
                lines.append(f'#define {tag}_BUS              "{comp.bus_name}"')
            if comp.bus.get("cs"):
                lines.append(f'#define {tag}_CS_PIN           "{comp.bus["cs"]}"')
        lines.append("")

    lines.append(f"#endif /* {name}_PINS_H */")
    return "\n".join(lines) + "\n"


