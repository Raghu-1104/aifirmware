def _uart_baud(board: BoardProfile) -> int:
    for bus in board.buses:
        if str(bus.get("type", "")).lower() in ("uart", "usart") and bus.get("baud"):
            return int(bus["baud"])
    return 115200


def gen_zephyr_overlay(board: BoardProfile) -> str:
    lines = [
        "/* Generated by fwcopilot from board.yaml.",
        " * Node labels (&i2c1, &spi1) must match your Zephyr board's devicetree.",
        " */",
        "",
    ]
    for bus in board.buses:
        btype = str(bus.get("type", "")).lower()
        label = _lower(bus.get("name"))
        devices = [c for c in board.components if c.bus_name == bus.get("name")]
        if btype not in ("i2c", "spi") or not devices:
            continue
        lines.append(f"&{label} {{")
        lines.append('    status = "okay";')
        if btype == "i2c" and bus.get("speed_hz"):
            speed = int(bus["speed_hz"])
            lines.append(f"    clock-frequency = <{'I2C_BITRATE_FAST' if speed >= 400000 else 'I2C_BITRATE_STANDARD'}>;")
        for comp in devices:
            node = _lower(comp.part or comp.ref)
            if btype == "i2c" and comp.address is not None:
                addr = _addr_literal(comp.address)
                lines.append(f"    {node}: {node}@{addr[2:].lower()} {{")
                lines.append(f'        compatible = "TODO,{node}";')
                lines.append(f"        reg = <{addr}>;")
                lines.append('        status = "okay";')
                lines.append("    };")
            elif btype == "spi":
                lines.append(f"    {node}: {node}@0 {{")
                lines.append(f'        compatible = "TODO,{node}";')
                lines.append("        reg = <0>;")
                lines.append(f"        spi-max-frequency = <{int(bus.get('speed_hz') or 1000000)}>;")
                lines.append('        status = "okay";')
                lines.append("    };")
        lines.append("};")
        lines.append("")
    return "\n".join(lines) or "/* No I2C/SPI devices declared in board.yaml. */\n"


def gen_zephyr_prj(board: BoardProfile) -> str:
    lines = ["# Generated by fwcopilot from board.yaml.", "CONFIG_LOG=y", "CONFIG_GPIO=y"]
    types = {str(b.get("type", "")).lower() for b in board.buses}
    if "i2c" in types:
        lines.append("CONFIG_I2C=y")
    if "spi" in types:
        lines.append("CONFIG_SPI=y")
    if types & {"uart", "usart"}:
        lines.append("CONFIG_SERIAL=y")
        lines.append("CONFIG_UART_INTERRUPT_DRIVEN=y")
    if any(str(c.role or "").lower().find("sensor") >= 0 for c in board.components):
        lines.append("CONFIG_SENSOR=y")
    return "\n".join(lines) + "\n"


