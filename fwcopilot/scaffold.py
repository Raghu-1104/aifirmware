def gen_main(board: BoardProfile) -> str:
    comps = [c for c in board.components if _bus_type(board, c) in ("i2c", "spi")]
    includes = "\n".join(f'#include "drivers/{_lower(c.part or c.ref)}.h"' for c in comps)
    decls, inits = [], []
    for comp in comps:
        base = _lower(comp.part or comp.ref)
        decls.append(f"static {base}_t {base};")
        inits.append(
            f"    /* {comp.ref}: {comp.part} on {comp.bus_name or 'unspecified bus'} */\n"
            f"    if ({base}_init(&{base}) != 0) {{\n"
            f"        board_fault(\"{base} init failed\");\n"
            f"    }}"
        )
    return f"""\
/* Generated by fwcopilot from board.yaml — application entry point.
 * Board: {board.name}
 */
#include <stdint.h>
#include "board_pins.h"
{includes}

{chr(10).join(decls)}

static void board_fault(const char *what)
{{
    (void)what;  /* TODO: log over {_first_uart(board)} and/or blink the status LED. */
    for (;;) {{
        __asm__ volatile("nop");
    }}
}}

static void board_init(void)
{{
    /* TODO: clock tree to BOARD_SYSCLK_HZ, then GPIO, then the buses below. */
{chr(10).join(f"    /* init {b.get('name')} ({b.get('type')}) */" for b in board.buses) or "    /* no buses declared in board.yaml */"}

    /* TODO: wire each device's transport callbacks to your HAL before init. */
{chr(10).join(inits) if inits else "    /* no bus-attached components declared in board.yaml */"}
}}

int main(void)
{{
    board_init();

    for (;;) {{
        /* TODO: application loop. */
    }}
}}
"""


def _first_uart(board: BoardProfile) -> str:
    for bus in board.buses:
        if str(bus.get("type", "")).lower() in ("uart", "usart"):
            return str(bus.get("name"))
    return "the debug UART"


