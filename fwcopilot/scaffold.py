def gen_makefile(board: BoardProfile) -> str:
    mcu = board.mcu
    core = str(mcu.get("core") or "Cortex-M4").lower()
    if "m0" in core:
        cpu, fpu = "cortex-m0", ""
    elif "m33" in core:
        cpu, fpu = "cortex-m33", "-mfpu=fpv5-sp-d16 -mfloat-abi=hard"
    elif "m7" in core:
        cpu, fpu = "cortex-m7", "-mfpu=fpv5-d16 -mfloat-abi=hard"
    elif "m4" in core:
        cpu, fpu = "cortex-m4", "-mfpu=fpv4-sp-d16 -mfloat-abi=hard" if "f" in core else ""
    else:
        cpu, fpu = "cortex-m3", ""
    target = _lower(board.name)
    return f"""\
# Generated by fwcopilot from board.yaml ({mcu.get('part', 'unknown MCU')}).
TARGET  := {target}
BUILD   := build

CROSS   := arm-none-eabi-
CC      := $(CROSS)gcc
OBJCOPY := $(CROSS)objcopy
SIZE    := $(CROSS)size

CPUFLAGS := -mcpu={cpu} -mthumb {fpu}
CFLAGS   := $(CPUFLAGS) -std=c11 -Og -g3 -Wall -Wextra -Wshadow -Wundef \\
            -ffunction-sections -fdata-sections -I. -Idrivers
LDFLAGS  := $(CPUFLAGS) -T{target}.ld -Wl,--gc-sections -Wl,-Map=$(BUILD)/$(TARGET).map \\
            --specs=nano.specs --specs=nosys.specs

SRCS := $(wildcard *.c) $(wildcard drivers/*.c)
OBJS := $(patsubst %.c,$(BUILD)/%.o,$(SRCS))

all: $(BUILD)/$(TARGET).bin

$(BUILD)/%.o: %.c
\t@mkdir -p $(dir $@)
\t$(CC) $(CFLAGS) -c $< -o $@

$(BUILD)/$(TARGET).elf: $(OBJS)
\t$(CC) $(OBJS) $(LDFLAGS) -o $@
\t$(SIZE) $@

$(BUILD)/$(TARGET).bin: $(BUILD)/$(TARGET).elf
\t$(OBJCOPY) -O binary $< $@

clean:
\trm -rf $(BUILD)

.PHONY: all clean
"""


